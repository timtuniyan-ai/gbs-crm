#!/bin/bash

echo "🚀 Развертывание GBS CRM..."

# Получить последние изменения из GitHub
echo "📥 Получение обновлений из GitHub..."
git pull origin main

# Остановить текущий контейнер
echo "⏹️ Остановка текущего контейнера..."
docker-compose down

# Пересобрать образ с новыми изменениями
echo "🔨 Сборка нового образа..."
docker-compose build --no-cache

# Запустить обновленный контейнер
echo "▶️ Запуск обновленного контейнера..."
docker-compose up -d

# Показать статус
echo "📊 Статус контейнеров:"
docker-compose ps

echo "✅ Развертывание завершено!"
echo "🌐 Приложение доступно на порту 3000"
